RHYME_FINALS: Mapping[str, str] = MappingProxyType(_FINAL_TO_GROUP)
RHYME_GROUPS: Mapping[str, str] = MappingProxyType(_GROUP_NAMES)


def _validate_char(char: str) -> str:
    """校验入参是单个字符并返回它。"""
    if not isinstance(char, str):
        raise ValueError("字符必须是字符串，当前类型为 %s" % type(char).__name__)
    if len(char) != 1:
        raise ValueError("字符必须恰好为一个汉字，当前为 %r" % (char,))
    return char


def final_of(char: str) -> Optional[str]:
    """返回单字的普通话韵母（教学字表内），字表外返回 None。"""
    name = _validate_char(char)
    return _CHAR_FINAL.get(name)


def rhyme_group(char: str) -> Optional[str]:
    """返回单字所属韵部的键（如 "ang"），无法判断时返回 None。"""
    final = final_of(char)
    if final is None:
        return None
    return _FINAL_TO_GROUP.get(final)


def rhyme_name(char: str) -> Optional[str]:
    """返回单字所属韵部的中文名（如「阳韵（ang/iang/uang）」）。"""
    group = rhyme_group(char)
    if group is None:
        return None
    return _GROUP_NAMES.get(group)
